// Helper to generate realistic historical trend line ending at currentPrice
function generateStockHistory(currentPrice: number, volatility: number = 0.08): { date: string; price: number }[] {
  const points = 30;
  const history: { date: string; price: number }[] = [];
  const now = new Date("2026-10-15T09:15:00Z");

  // Work backwards from current price
  let tempPrice = currentPrice;
  const prices: number[] = [currentPrice];

  for (let i = 1; i < points; i++) {
    // Generate slight trend and noise
    const delta = (Math.sin(i * 0.4) * 0.015 + (Math.random() - 0.48) * volatility) * tempPrice;
    tempPrice = Math.max(10, tempPrice - delta);
    prices.unshift(Math.round(tempPrice * 100) / 100);
  }

  // Assign dates for the last 30 business days
  for (let i = 0; i < points; i++) {
    const d = new Date(now);
    d.setDate(d.getDate() - (points - 1 - i));
    history.push({
      date: d.toISOString().split("T")[0],
      price: prices[i],
    });
  }

  return history;
}

